"""Builds app/src/main/assets/ui/glyphs.css: a tiny font with the terminal symbols that Claude Code
and Codex draw but Android's fonts miss (⏵⏵ showed up as □□ on a phone), so the 「终端」 screens
render them, one cell wide, on every device. Plain polygons, drawn here; no third-party outlines.

Run on a machine with fontTools: python3 scripts/make_term_glyphs.py"""
import base64, io, math
from pathlib import Path
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

UPEM, ADV, MID = 1000, 600, 330   # one monospace cell; MID ≈ the math axis of the mono fonts used


def area(pts): return sum(x0 * y1 - x1 * y0 for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1])) / 2


def clockwise(pts): return pts[::-1] if area(pts) > 0 else pts  # TrueType: outer contours clockwise


def rect(x0, y0, x1, y1): return [(x0, y0), (x0, y1), (x1, y1), (x1, y0)]


def bar(cx, cy, length, width, deg):
    """A stroke centred on (cx, cy), rotated by deg."""
    a = math.radians(deg); dx, dy = math.cos(a), math.sin(a); nx, ny = -dy, dx
    l, w = length / 2, width / 2
    return [(cx + dx * sx * l + nx * sy * w, cy + dy * sx * l + ny * sy * w) for sx, sy in ((-1, -1), (1, -1), (1, 1), (-1, 1))]


def star(cx, cy, points, outer, inner, rot=90):
    out = []
    for i in range(points * 2):
        r = outer if i % 2 == 0 else inner; a = math.radians(rot + i * 180 / points)
        out.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return out


def circle(cx, cy, r, n=28): return [(cx + r * math.cos(2 * math.pi * i / n), cy + r * math.sin(2 * math.pi * i / n)) for i in range(n)]


def spokes(n, length, width, deg0=90): return [bar(300, MID, length, width, deg0 + i * 180 / n) for i in range(n)]


GLYPHS = {
    0x23F5: [[(130, MID - 260), (500, MID), (130, MID + 260)]],               # ⏵
    0x23F4: [[(470, MID - 260), (100, MID), (470, MID + 260)]],               # ⏴
    0x23F6: [[(80, MID - 180), (520, MID - 180), (300, MID + 220)]],          # ⏶
    0x23F7: [[(80, MID + 180), (520, MID + 180), (300, MID - 220)]],          # ⏷
    0x23F8: [rect(110, MID - 250, 245, MID + 250), rect(355, MID - 250, 490, MID + 250)],  # ⏸
    0x23F9: [rect(100, MID - 210, 500, MID + 190)],                           # ⏹
    0x23FA: [circle(300, MID, 215)],                                          # ⏺
    0x23BF: [[(170, 900), (230, 900), (230, MID + 30), (600, MID + 30), (600, MID - 30), (170, MID - 30)]],  # ⎿
    0x23CE: [[(430, 720), (520, 720), (520, 240), (250, 240), (250, 110), (60, 285), (250, 460), (250, 330), (430, 330)]],  # ⏎
    0x2303: [[(110, MID + 20), (300, MID + 260), (490, MID + 20), (430, MID - 20), (300, MID + 150), (170, MID - 20)]],  # ⌃
    0x276F: [[(110, MID + 290), (260, MID + 290), (510, MID), (260, MID - 290), (110, MID - 290), (360, MID)]],  # ❯
    0x2714: [[(70, MID + 20), (160, MID + 110), (250, MID - 20), (470, MID + 260), (550, MID + 170), (250, MID - 200)]],  # ✔
    0x2717: [bar(300, MID, 470, 85, 55), bar(300, MID, 470, 85, 125)],          # ✗
    0x2722: [star(300, MID, 4, 260, 70)],                                     # ✢
    0x2733: spokes(4, 480, 70),                                               # ✳
    0x2736: [star(300, MID, 6, 250, 125)],                                    # ✶
    0x273B: spokes(3, 500, 95, 90),                                           # ✻
    0x273D: spokes(4, 500, 110, 90),                                          # ✽
}


def build():
    names = [".notdef"] + ["u%04X" % cp for cp in sorted(GLYPHS)]
    fb = FontBuilder(UPEM, isTTF=True)
    fb.setupGlyphOrder(names)
    fb.setupCharacterMap({cp: "u%04X" % cp for cp in GLYPHS})
    glyphs = {".notdef": TTGlyphPen(None).glyph()}
    for cp, contours in GLYPHS.items():
        pen = TTGlyphPen(None)
        for pts in contours:
            pts = clockwise([(round(x), round(y)) for x, y in pts])
            pen.moveTo(pts[0])
            for p in pts[1:]: pen.lineTo(p)
            pen.closePath()
        glyphs["u%04X" % cp] = pen.glyph()
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics({n: (ADV, 0) for n in names})
    fb.setupHorizontalHeader(ascent=900, descent=-250)
    fb.setupNameTable({"familyName": "Pocket Term Glyphs", "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=900, sTypoDescender=-250, usWinAscent=900, usWinDescent=250, xAvgCharWidth=ADV)
    fb.setupPost(isFixedPitch=1)
    out = io.BytesIO(); fb.save(out); return out.getvalue()


def ranges(cps):
    cps = sorted(cps); spans = []
    for cp in cps:
        if spans and cp == spans[-1][1] + 1: spans[-1][1] = cp
        else: spans.append([cp, cp])
    return ",".join("U+%04X" % a if a == b else "U+%04X-%04X" % (a, b) for a, b in spans)


if __name__ == "__main__":
    data = base64.b64encode(build()).decode()
    css = ("/* Generated by scripts/make_term_glyphs.py: terminal symbols Android fonts miss (⏵ ⏸ ⎿ ⏎ ✻ …),\n"
           " * one cell wide. --term-font lists this family first; unicode-range keeps it to these glyphs. */\n"
           "@font-face{font-family:'Pocket Term Glyphs';font-display:block;unicode-range:%s;"
           "src:url(data:font/ttf;base64,%s) format('truetype')}\n" % (ranges(GLYPHS), data))
    target = Path(__file__).resolve().parents[1] / "app/src/main/assets/ui/glyphs.css"
    target.write_text(css)
    print(target, len(css))
